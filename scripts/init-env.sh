#!/usr/bin/env bash
# Generates the repo-root .env with fresh random secrets. Refuses to overwrite an existing .env.
set -euo pipefail

cd "$(dirname "$0")/.."

if [ -e .env ]; then
  echo "init-env: .env already exists; refusing to overwrite it (delete it first to regenerate)." >&2
  exit 1
fi

secret() { openssl rand -hex 32; }

if [ -n "${CODESPACE_NAME:-}" ]; then
  allowed_origins="https://${CODESPACE_NAME}-5173.${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:-app.github.dev}"
else
  allowed_origins="http://localhost:5173"
fi

postgres_password=$(secret)
support_db_password=$(secret)
billing_db_password=$(secret)

umask 077
cat > .env <<ENV
# Generated by scripts/init-env.sh. Never commit this file.
POSTGRES_PASSWORD=${postgres_password}
SUPPORT_DB_PASSWORD=${support_db_password}
BILLING_DB_PASSWORD=${billing_db_password}

# Host-side URLs (tests, local runs). Services inside compose use host "db" instead of localhost.
SUPPORT_DATABASE_URL=postgresql+psycopg://support_app:${support_db_password}@localhost:5432/uas
BILLING_DATABASE_URL=postgresql+psycopg://billing_app:${billing_db_password}@localhost:5432/uas
SUPPORT_TEST_DATABASE_URL=postgresql+psycopg://support_app:${support_db_password}@localhost:5432/uas_test
BILLING_TEST_DATABASE_URL=postgresql+psycopg://billing_app:${billing_db_password}@localhost:5432/uas_test

BILLING_API_KEY=$(secret)
FAULT_ADMIN_KEY=$(secret)
IDENTIFIER_HASH_KEY=$(secret)

ALLOWED_ORIGINS=${allowed_origins}

LLM_PROVIDER=scripted
LIVE_LLM_ENABLED=false
OPENAI_API_KEY=
ENV

echo "init-env: wrote .env"
